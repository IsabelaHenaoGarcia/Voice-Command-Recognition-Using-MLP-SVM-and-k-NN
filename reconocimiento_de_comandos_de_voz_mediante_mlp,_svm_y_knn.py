# ==============================================================================
SR = 16000
N_MFCC = 40
N_FFT = 512
HOP = 160
WIN = 400
MAX_FRAMES = 98

def load_wav_mono(path, sr=SR):
    y, sr0 = sf.read(str(path), dtype="float32")
    if y.ndim > 1:
        y = np.mean(y, axis=1)
    if sr0 != sr:
        y = librosa.resample(y, orig_sr=sr0, target_sr=sr)
    return y

def wav_to_mfcc(y, sr=SR, n_mfcc=N_MFCC, max_frames=MAX_FRAMES):
    y = np.append(y[0], y[1:] - 0.97*y[:-1])
    mfcc = librosa.feature.mfcc(y=y, sr=sr, n_mfcc=n_mfcc, n_fft=N_FFT,
                                hop_length=HOP, win_length=WIN)
    if mfcc.shape[1] < max_frames:
        pad = max_frames - mfcc.shape[1]
        mfcc = np.pad(mfcc, ((0,0),(0,pad)), mode="constant")
    else:
        mfcc = mfcc[:, :max_frames]
    return mfcc.astype(np.float32)

def build_dataset(data_dir=DATA_DIR, classes=None):
    X, y, paths = [], [], []
    classes = classes or CLASSES
    for idx, c in enumerate(classes):
        for wav in (data_dir/c).glob("*.wav"):
            try:
                ysig = load_wav_mono(wav)
                feat = wav_to_mfcc(ysig)
                X.append(feat)
                y.append(idx)
                paths.append(wav)
            except Exception:
                pass
    X = np.stack(X)
    y = np.array(y, dtype=np.int64)
    paths = np.array(paths)
    return X, y, paths

