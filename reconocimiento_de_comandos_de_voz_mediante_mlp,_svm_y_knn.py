# CELDA 6: IMPLEMENTACIÓN DE MLP
# ===============================
def relu(x):
    return np.maximum(0, x)

def d_relu(x):
    return (x > 0).astype(x.dtype)

def softmax(z):
    z = z - z.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=1, keepdims=True)

def one_hot(y, K):
    Y = np.zeros((y.size, K), dtype=np.float32)
    Y[np.arange(y.size), y] = 1.0
    return Y

class MLP:
    def __init__(self, in_dim, h1=256, h2=128, out_dim=4, l2=1e-4, seed=42):
        rng = np.random.default_rng(seed)
        self.in_dim, self.h1, self.h2, self.out_dim = in_dim, h1, h2, out_dim
        self.l2 = float(l2)

        self.W1 = rng.normal(0, np.sqrt(2.0/in_dim), (in_dim, h1)).astype(np.float32)
        self.b1 = np.zeros(h1, dtype=np.float32)

        self.W2 = rng.normal(0, np.sqrt(2.0/h1), (h1, h2)).astype(np.float32)
        self.b2 = np.zeros(h2, dtype=np.float32)

        self.W3 = rng.normal(0, np.sqrt(2.0/h2), (h2, out_dim)).astype(np.float32)
        self.b3 = np.zeros(out_dim, dtype=np.float32)

        self.cache = {}

    def forward(self, X):
        z1 = X @ self.W1 + self.b1
        h1 = relu(z1)

        z2 = h1 @ self.W2 + self.b2
        h2 = relu(z2)

        z3 = h2 @ self.W3 + self.b3
        out = softmax(z3)

        self.cache = {'X': X, 'z1': z1, 'h1': h1, 'z2': z2, 'h2': h2, 'z3': z3, 'out': out}
        return out

    def loss(self, Yh, Y):
        eps = 1e-8
        ce = -np.mean(np.sum(Y * np.log(Yh + eps), axis=1))
        l2_reg = 0.5 * self.l2 * (np.sum(self.W1**2) + np.sum(self.W2**2) + np.sum(self.W3**2))
        return ce + l2_reg

    def backward(self, X, Y):
        m = X.shape[0]
        dz3 = self.cache['out'] - Y

        dW3 = (self.cache['h2'].T @ dz3) / m + self.l2 * self.W3
        db3 = np.mean(dz3, axis=0)

        dh2 = dz3 @ self.W3.T
        dz2 = dh2 * d_relu(self.cache['z2'])
        dW2 = (self.cache['h1'].T @ dz2) / m + self.l2 * self.W2
        db2 = np.mean(dz2, axis=0)

        dh1 = dz2 @ self.W2.T
        dz1 = dh1 * d_relu(self.cache['z1'])
        dW1 = (X.T @ dz1) / m + self.l2 * self.W1
        db1 = np.mean(dz1, axis=0)

        return {'dW1': dW1, 'db1': db1, 'dW2': dW2, 'db2': db2, 'dW3': dW3, 'db3': db3}

    def step(self, grads, lr):
        self.W1 -= lr * grads['dW1']
        self.b1 -= lr * grads['db1']
        self.W2 -= lr * grads['dW2']
        self.b2 -= lr * grads['db2']
        self.W3 -= lr * grads['dW3']
        self.b3 -= lr * grads['db3']

    def fit(self, X, y, epochs=20, lr=5e-3, batch=128, Xv=None, yv=None, verbose=True):
        Y = one_hot(y, self.out_dim)
        hist = {"loss":[], "val_loss":[]}
        n = len(X)

        for ep in range(epochs):
            perm = np.random.permutation(n)
            Xs, Ys = X[perm], Y[perm]

            for i in range(0, n, batch):
                xb = Xs[i:i+batch]
                yb = Ys[i:i+batch]
                yh = self.forward(xb)
                grads = self.backward(xb, yb)
                self.step(grads, lr)

            yh_train = self.forward(X)
            loss_train = self.loss(yh_train, Y)
            hist["loss"].append(loss_train)

            if Xv is not None and yv is not None:
                Yv = one_hot(yv, self.out_dim)
                yh_val = self.forward(Xv)
                loss_val = self.loss(yh_val, Yv)
                hist["val_loss"].append(loss_val)

                if verbose:
                    print(f"Epoch {ep+1}/{epochs} - loss={loss_train:.4f} - val_loss={loss_val:.4f}")
            else:
                if verbose:
                    print(f"Epoch {ep+1}/{epochs} - loss={loss_train:.4f}")

        return hist

    def predict(self, X):
        out = self.forward(X)
        return np.argmax(out, axis=1)

